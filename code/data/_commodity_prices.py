def price_decline_lookup(prices: dict[tuple[int, int], float], months: int) -> dict[tuple[int, int], float]:
    """Build a month lookup for positive percentage declines over a trailing window."""
    rows = sorted(prices.items())
    keys = [k for k, _ in rows]
    vals = [v for _, v in rows]
    decline = {}
    for i, (yr, mo) in enumerate(keys):
        if i < months:
            continue
        prev_yr, prev_mo = keys[i - months]
        gap_months = (yr - prev_yr) * 12 + (mo - prev_mo)
        if gap_months != months:
            continue
        chg = (vals[i] - vals[i - months]) / vals[i - months]
        decline[(yr, mo)] = max(-chg, 0.0)
    return decline


